ZAI_BASE_URL = "https://chat.z.ai/"

# Only model confirmed working on the anonymous guest endpoint.
AVAILABLE_MODELS = ["GLM-5.3-Flash"]

DEFAULT_TIMEOUT = 180

# Markers that bound the assistant reply within the page text (everything past
# the first footer marker is page-chrome, not the model's answer).
_FOOTER_MARKERS = (
    "Connect IM",
    "Generated by AI",
    "Tech Blog",
    "Contact us",
    "Terms of Service",
    "Privacy Policy",
    "Sign in",
    "Home",
    "ZCode",
    "API",
    "More than coding",
    "Full-Stack",
    "Writing",
    "Data Insight",
    "PPT",
    "Web Site",
    "GLM-5.3-Flash",
    "GLM-5.3",
)

# Persistent browser session (reused across turns).
_zai_session = None
_zai_session_lock = threading.Lock()
_zai_initialized = False


def _build_zai_script(prompt: str) -> str:
    """Build the in-page script that types ``prompt`` and hits send."""
    return r"""
(async () => {
  try {
    const sel = document.querySelector('textarea, [contenteditable="true"]');
    if (!sel) return 'ERR:no input';
    sel.focus();
    sel.textContent = __PROMPT__;
    sel.dispatchEvent(new Event('input', {bubbles: true}));
    await new Promise((r) => setTimeout(r, 1000));
    const btn = document.querySelector('.sendMessageButton');
    if (!btn) return 'ERR:no btn';
    if (btn.disabled) return 'ERR:disabled';
    btn.click();
    return 'SENT';
  } catch (e) {
    return 'ERR:' + String(e);
  }
})()
""".replace("__PROMPT__", json.dumps(prompt))


def _extract_reply(body: str, user_prompt: str) -> str:
    """Extract the assistant's reply from the full page text.

    The reply follows the user's message and ends at the first page-chrome
    footer marker.
    """
    if not body:
        return ""
    idx = body.rfind(user_prompt)
    if idx == -1:
        # Fallback: return everything before the first footer marker.
        body = _cut_footer(body)
        return body.strip()
    tail = body[idx + len(user_prompt):]
    tail = _cut_footer(tail)
    return tail.strip()


def _cut_footer(text: str) -> str:
    cut = len(text)
    for marker in _FOOTER_MARKERS:
        pos = text.find(marker)
        if pos != -1 and pos < cut:
            cut = pos
    return text[:cut]


async def _wait_for_idle(session: CDPSession, attempts: int = 40) -> None:
    """Wait for the chat input and send button to become interactive."""
    for _ in range(attempts):
        try:
            ready = await session.evaluate_js(
                "!!document.querySelector('.sendMessageButton') && "
                "!!document.querySelector('textarea, [contenteditable=\"true\"]')"
            )
            if ready:
                return
        except Exception:
            pass
        await asyncio.sleep(0.5)


async def _ensure_session() -> CDPSession:
    global _zai_session, _zai_initialized
    if _zai_session is not None and _zai_initialized:
        try:
            await _zai_session.get_title()
            return _zai_session
        except Exception:
            try:
                await _zai_session.close()
            except Exception:
                pass
            _zai_session = None
            _zai_initialized = False

    with _zai_session_lock:
        if _zai_session is not None and _zai_initialized:
            try:
                await _zai_session.get_title()
                return _zai_session
            except Exception:
                try:
                    await _zai_session.close()
                except Exception:
                    pass
                _zai_session = None
                _zai_initialized = False

        session = CDPSession(headless=True, engine="chrome")
        await session.start()
        await session.navigate(ZAI_BASE_URL)
        await _wait_for_idle(session)
        _zai_session = session
        _zai_initialized = True
        return session


async def _run_browser(
    messages: List[Dict[str, Any]],
    timeout: int,
    output: "queue.Queue",
) -> None:
    """Drive the Z.ai web UI and push the assistant reply onto ``output``."""
    try:
        session = await _ensure_session()
        prompt = ""
        for msg in reversed(messages):
            if msg.get("role") == "user":
                prompt = str(msg.get("content") or "")
                break
        if not prompt:
            output.put(("error", "Z.ai requires at least one user message"))
            return

        await session.evaluate_js_stdin(_build_zai_script(prompt))

        deadline = time.time() + timeout
        current = ""
        stable_since = None
        while time.time() < deadline:
            await asyncio.sleep(0.5)
            try:
                body = await session.evaluate_js("document.body.innerText || ''")
            except Exception:
                body = ""
            if isinstance(body, str):
                reply = _extract_reply(body, prompt)
                if reply and reply != current:
                    delta = reply[len(current):]
                    if delta:
                        output.put(("delta", delta))
                        current = reply
                    stable_since = time.time()
            # Treat the reply as finished once it has been stable for ~2s.
            if current and stable_since and (time.time() - stable_since) >= 2.0:
                break

        if current:
            output.put(("done", None))
        else:
            output.put(("error", f"timed out after {timeout}s waiting for Z.ai"))
    except Exception as exc:
        output.put(("error", str(exc)))
        global _zai_session, _zai_initialized
        if _zai_session:
            try:
                await _zai_session.close()
            except Exception:
                pass
            _zai_session = None
            _zai_initialized = False


def _stream_conversation(
    messages: List[Dict[str, Any]], timeout: int = DEFAULT_TIMEOUT
) -> Generator[str, None, None]:
    """Yield assistant deltas, retrying once with a fresh session on failure."""
    last_error = ""
    for attempt in range(2):
        output: "queue.Queue" = queue.Queue()

        def worker() -> None:
            try:
                asyncio.run(_run_browser(messages, timeout, output))
            except Exception as exc:  # pragma: no cover - defensive
                output.put(("error", str(exc)))

        thread = threading.Thread(target=worker, daemon=True)
        thread.start()

        try:
            while True:
                try:
                    kind, value = output.get(timeout=timeout + 60)
                except queue.Empty as exc:
                    raise IOError("Z.ai browser request timed out") from exc
                if kind == "delta" and value:
                    yield value
                elif kind == "error":
                    last_error = value or "unknown error"
                    break  # exit inner loop to retry
                elif kind == "done":
                    return
        except IOError:
            last_error = "Z.ai browser request timed out"
            break

        # Reset the persistent session and retry once.
        global _zai_session, _zai_initialized
        _zai_session = None
        _zai_initialized = False
        if attempt == 0:
            continue
        raise IOError(f"Z.ai request failed: {last_error}")


class Completions(BaseCompletions):
    def __init__(self, client: "Zai"):
        self._client = client

    def create(
        self,
        *,
        model: str,
        messages: List[Dict[str, str]],
        max_tokens: Optional[int] = None,
        stream: bool = False,
        temperature: Optional[float] = None,
        top_p: Optional[float] = None,
        timeout: Optional[int] = None,
        proxies: Optional[dict] = None,
        tools: ToolList = None,
        tool_choice: Optional[Union[str, Dict[str, Any]]] = None,
        **kwargs: Any,
    ) -> Any:
        del max_tokens, temperature, top_p, proxies, tools, tool_choice, kwargs
        request_id = f"chatcmpl-{uuid.uuid4()}"
        created_time = int(time.time())
        actual_timeout = timeout or self._client.timeout

        if stream:
            return self._create_stream(request_id, created_time, model, messages, actual_timeout)
        return self._create_non_stream(request_id, created_time, model, messages, actual_timeout)

    def _create_stream(
        self,
        request_id: str,
        created_time: int,
        model: str,
        messages: List[Dict[str, Any]],
        timeout: int,
    ) -> Generator[ChatCompletionChunk, None, None]:
        for delta_text in _stream_conversation(messages, timeout):
            yield ChatCompletionChunk(
                id=request_id,
                choices=[
                    Choice(
                        index=0,
                        delta=ChoiceDelta(content=delta_text, role="assistant"),
                        finish_reason=None,
                    )
                ],
                created=created_time,
                model=model,
            )
        yield ChatCompletionChunk(
            id=request_id,
            choices=[Choice(index=0, delta=ChoiceDelta(content=None), finish_reason="stop")],
            created=created_time,
            model=model,
        )

    def _create_non_stream(
        self,
        request_id: str,
        created_time: int,
        model: str,
        messages: List[Dict[str, Any]],
        timeout: int,
    ) -> ChatCompletion:
        content = "".join(_stream_conversation(messages, timeout))
        message = ChatCompletionMessage(role="assistant", content=content)
        choice = Choice(index=0, message=message, finish_reason="stop")
        usage = CompletionUsage(prompt_tokens=0, completion_tokens=0, total_tokens=0)
        return ChatCompletion(
            id=request_id,
            choices=[choice],
            created=created_time,
            model=model,
            usage=usage,
        )


class Chat(BaseChat):
    def __init__(self, client: "Zai"):
        self.completions = Completions(client)


class Zai(OpenAICompatibleProvider):
    """OpenAI-compatible client for anonymous Z.ai (chat.z.ai).

    Uses a persistent Chromium browser session so the page's captcha and
    anti-bot protections are handled inside the browser.

    Usage:
        client = Zai()
        response = client.chat.completions.create(
            model="GLM-5.3-Flash",
            messages=[{"role": "user", "content": "Hello!"}],
        )
    """

    required_auth = False
    AVAILABLE_MODELS = AVAILABLE_MODELS
    default_model = "GLM-5.3-Flash"

    def __init__(
        self,
        api_key: Optional[str] = None,
        timeout: int = DEFAULT_TIMEOUT,
        proxies: Optional[Dict[str, str]] = None,
    ):
        super().__init__(proxies=proxies)
        self.timeout = timeout
        self.api_key = api_key
        self.chat = Chat(self)

    @classmethod
    def get_models(cls, api_key: Optional[str] = None) -> List[str]:
        del api_key
        return list(cls.AVAILABLE_MODELS)

    @property
    def models(self) -> SimpleModelList:
        return SimpleModelList(list(type(self).AVAILABLE_MODELS))


