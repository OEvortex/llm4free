"""OpenAI-compatible provider for anonymous Z.ai (chat.z.ai).

The anonymous web client is driven through a real browser session so that the
page's own Cloudflare/anti-bot handling and the Aliyun slider captcha are
resolved inside the browser (the Chromium engine solves the captcha
automatically).  No request-signing or captcha reverse-engineering is required
here.

All requests run through :class:`llm4free.browser_requests.cdp.CDPSession`
using the ``chrome`` engine, with a *persistent* browser session reused across
turns (like :mod:`llm4free.llm.venice`).
"""

